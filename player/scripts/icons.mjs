// Writes src/app/shared/icon-data.ts: the Phosphor duotone icons the app uses (docs/design/broadsheet.md), as SVG
// markup, so only these ship instead of the whole icon font. Run after changing ICONS: node scripts/icons.mjs
import { readFileSync, writeFileSync } from 'node:fs';

// The name the app uses: the Phosphor icon (and weight, duotone unless given)
const ICONS = {
  ArrowLeft: 'arrow-left', ArrowLeftRight: 'arrows-left-right', ArrowRight: 'arrow-right', BadgeCheck: 'seal-check',
  Bell: 'bell', CalendarDays: 'calendar-dots', Check: 'check', CheckCheck: 'checks', ChevronRight: 'caret-right',
  CircleCheck: 'check-circle', CircleUser: 'user-circle', CircleX: 'x-circle', Clock: 'clock', Coins: 'coins',
  Compass: 'compass', Eye: 'eye', EyeOff: 'eye-slash', Flag: 'flag', Heart: 'heart', Hourglass: 'hourglass',
  House: 'house', LoaderCircle: 'circle-notch', LogIn: 'sign-in', LogOut: 'sign-out', MapPin: 'map-pin',
  MessageSquare: 'chat-circle', Minus: 'minus', Phone: 'phone', Plus: 'plus', Search: 'magnifying-glass',
  SendHorizontal: 'paper-plane-right', ShareNetwork: 'share-network', ShieldCheck: 'shield-check', Shirt: 't-shirt',
  Star: 'star', TimerOff: 'timer', Trash2: 'trash', Trophy: 'trophy', Users: 'users', Wallet: 'wallet', X: 'x',
};

const root = new URL('../node_modules/@phosphor-icons/core/assets/duotone/', import.meta.url);
const lines = Object.entries(ICONS).map(([name, file]) => {
  const svg = readFileSync(new URL(`${file}-duotone.svg`, root), 'utf8');
  const inner = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').trim();
  return `export const ${name}: IconData = '${inner.replaceAll("'", "\\'")}';`;
});
writeFileSync(new URL('../src/app/shared/icon-data.ts', import.meta.url), `// Generated by scripts/icons.mjs from @phosphor-icons/core (duotone, 256 x 256). Don't edit by hand.

/** An icon's SVG markup, inside a 256 x 256 view box. */
export type IconData = string;

${lines.join('\n')}
`);
console.log(`${lines.length} icons`);
